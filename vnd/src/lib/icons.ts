export const ICONS: Record<string, Component> = Object.fromEntries(
  ICON_GROUPS.flatMap((g) => g.icons.map((i) => [i.name, i.icon] as const)),
)

export const ICON_NAMES = Object.keys(ICONS)

export const FALLBACK_ICON = 'Ellipsis'

export function iconComponent(name: string): Component {
  return ICONS[name] ?? ICONS[FALLBACK_ICON]!
}

/**
 * Отбрасываем окончание, чтобы «травы» находили по «трава», а «врачи» по
 * «врач». Полноценная морфология тут не нужна: слова в подписях короткие и
 * сравниваются по началу.
 */
function stem(word: string): string {
  return word.length > 4 ? word.replace(/[аяуюыиеёоэйь]{1,2}$/, '') : word
}

function tokens(text: string): string[] {
  return text.toLowerCase().split(/[^a-zа-яё0-9]+/i).filter(Boolean).map(stem)
}

function matches(def: IconDef, query: string[]): boolean {
  const haystack = tokens(`${def.label} ${def.alias ?? ''} ${def.name}`)
  return query.every((q) => haystack.some((word) => word.startsWith(q)))
}

/** Поиск по подписи и синонимам — чтобы не листать весь список руками. */
export function searchIcons(query: string): IconGroup[] {
  const q = tokens(query)
  if (q.length === 0) return ICON_GROUPS
  return ICON_GROUPS.map((g) => ({ title: g.title, icons: g.icons.filter((i) => matches(i, q)) })).filter(
    (g) => g.icons.length > 0,
  )
}
